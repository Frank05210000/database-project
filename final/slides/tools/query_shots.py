#!/usr/bin/env python3
"""Run phase4/sql_q/*.sql against the running e-Shop PostgreSQL container and save
psql-style PNG screenshots (via phase4/tools/term2png.py) for the slides and report.

Everything runs inside BEGIN … ROLLBACK, so the database is never changed
(views are created only for the duration of the transaction).

    python3 final/slides/tools/query_shots.py [--container NAME] [--out DIR]

If the database has no `v_orders` view yet (ORDERS.total decision pending), a
temporary `CREATE VIEW v_orders AS SELECT * FROM orders` is used and noted.
"""
import argparse

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SQL_Q = ROOT / "phase4" / "sql_q"
TERM2PNG = ROOT / "phase4" / "tools" / "term2png.py"
ORDER = ["v1_store_daily_sales", "v2_product_sales", "q1_store_best_seller",
         "q2_top_customers", "q3_store_rating", "q4_discount_usage"]
NEEDS_V2 = {"q1_store_best_seller"}
MAX_ROWS = 12


def psql(container, sql):
    r = subprocess.run(["docker", "exec", "-i", container, "sh", "-c",
                        'psql -X -q -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB"'],
                       input=sql, capture_output=True, text=True)
    return r.returncode, r.stdout, r.stderr


def statements(sql):
    body = "\n".join(l for l in sql.splitlines() if not l.strip().startswith("--"))
    return [s.strip() + ";" for s in body.split(";") if s.strip()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--container", default="eshop-implementation-b6539e-db-1")
    ap.add_argument("--out", default=str(ROOT / "final" / "slides" / "img" / "q"))
    a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)

    _, has, _ = psql(a.container, "SELECT to_regclass('v_orders') IS NOT NULL;\n")
    fallback = "t" not in has
    if fallback:
        print("! v_orders not found — using temporary v_orders = SELECT * FROM orders")

    v2_create = statements((SQL_Q / "v2_product_sales.sql").read_text())[0]
    for name in ORDER:
        stmts = statements((SQL_Q / f"{name}.sql").read_text())
        setup = [s for s in stmts if s.upper().startswith("CREATE")]
        shown = [s for s in stmts if not s.upper().startswith("CREATE")][-1]
        pre = (["CREATE VIEW v_orders AS SELECT * FROM orders;"] if fallback else []) + \
              ([v2_create] if name in NEEDS_V2 else []) + setup
        sql = "BEGIN;\n\\o /dev/null\n" + "\n".join(pre) + "\n\\o\n" + shown + "\nROLLBACK;\n"
        code, res, err = psql(a.container, sql)
        if code:
            print(f"✗ {name}: {err.strip()}"); continue
        lines = res.rstrip("\n").splitlines()
        if len(lines) > MAX_ROWS + 4:   # header(2) + rows + "(n rows)"
            lines = lines[:MAX_ROWS + 2] + ["   ...", lines[-1]]
        text = f"fuwa=# \\i {name}.sql\n" + "\n".join(lines)
        (out / f"{name}.txt").write_text(text)
        subprocess.run([sys.executable, str(TERM2PNG), str(out / f"{name}.png")], input=text, text=True, check=True)
    (out / "SOURCE.txt").write_text(
        f"container={a.container}\nv_orders_fallback={fallback}\n"
        "Generated by final/slides/tools/query_shots.py (BEGIN…ROLLBACK, read-only effect).\n")


if __name__ == "__main__":
    main()
